/**
 * 情绪词命中子串即返回对应 emoji；未知情绪给中性符号。
 * @param whenMissing 情绪缺失（null / 空串）时的占位符号；
 *   日记详情用 "🎙" 表示「仅有录音、未分析出情绪」的语义。
 */
export function emotionEmoji(emotion?: string | null, whenMissing = "😐"): string {
  if (!emotion) return whenMissing;
  for (const [word, emoji] of TABLE) {
    if (emotion.includes(word)) return emoji;
  }
  return "😐";
}
